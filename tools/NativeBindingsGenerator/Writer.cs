using System.Text;

namespace Magic.Tools.NativeBindingsGenerator;

/// <summary>
/// Lays the declarations out as one file: a static class per owner prefix holding its constants, types and functions,
/// a partial struct for functions that attach to one, and what has no owner in a class named for the library.
/// </summary>
internal static class Writer
{
    public static string Write(Options options, IReadOnlyList<Declaration> declarations, IReadOnlySet<string> structs)
    {
        List<string> owners = [];
        Dictionary<string, List<Declaration>> byOwner = new(StringComparer.Ordinal);
        string fallback = options.Class;
        foreach (Declaration declaration in declarations)
        {
            string owner = declaration.Owner.Length == 0 && declaration.Kind != DeclarationKind.Type ? fallback : declaration.Owner;
            if (!byOwner.TryGetValue(owner, out List<Declaration>? list))
            {
                list = [];
                byOwner[owner] = list;
                owners.Add(owner);
            }

            list.Add(declaration);
        }

        StringBuilder text = new();
        text.Append("// <auto-generated/>\n");
        text.Append("// ").Append(options.Library).Append(" from ").Append(string.Join(", ", options.Headers)).Append(", by tools/NativeBindingsGenerator. Edit the headers' NativeLibrary item, never this file.\n");
        text.Append("#pragma warning disable\n#nullable enable\n");
        text.Append("using System.Runtime.CompilerServices;\nusing System.Runtime.InteropServices;\n");

        text.Append('\n');
        text.Append("namespace ").Append(options.Namespace).Append(";\n");

        if (byOwner.TryGetValue("", out List<Declaration>? topLevel))
        {
            foreach (Declaration declaration in topLevel)
            {
                text.Append('\n').Append(declaration.Text.Replace("\npublic partial struct ", "\npublic unsafe partial struct ", StringComparison.Ordinal).Replace("\n[StructLayout(", "\n[StructLayout(", StringComparison.Ordinal));
            }
        }

        foreach (string owner in owners)
        {
            if (owner.Length == 0 || structs.Contains(owner))
            {
                continue;
            }

            text.Append('\n');
            Container(text, options, owner, $"public static unsafe partial class {owner}", byOwner, owners, structs, 0);
        }

        foreach (string owner in owners)
        {
            if (structs.Contains(owner) && Names.Split(owner, options.Prefixes).Owner.Length == 0)
            {
                text.Append('\n');
                Container(text, options, owner, $"public unsafe partial struct {Names.Pascal(owner)}", byOwner, owners, structs, 0);
            }
        }

        return text.ToString();
    }

    private static void Container(StringBuilder text, Options options, string owner, string header, Dictionary<string, List<Declaration>> byOwner, List<string> owners, IReadOnlySet<string> structs, int depth)
    {
        string indent = new(' ', depth * 4);
        text.Append(indent).Append(header).Append('\n').Append(indent).Append("{\n");
        List<Declaration> members = byOwner[owner];
        bool first = true;
        foreach (DeclarationKind kind in new[] { DeclarationKind.Constant, DeclarationKind.Type, DeclarationKind.Function })
        {
            if (kind == DeclarationKind.Function && HasFunctions(members))
            {
                Separate(text, ref first);
                text.Append(indent).Append("    private const string Library = \"").Append(options.Library).Append("\";\n");
            }

            foreach (Declaration declaration in members)
            {
                if (declaration.Kind == kind)
                {
                    Separate(text, ref first);
                    Indented(text, declaration.Text, depth + 1);
                }
            }
        }

        foreach (string child in owners)
        {
            if (structs.Contains(child) && string.Equals(Names.Split(child, options.Prefixes).Owner, owner, StringComparison.Ordinal))
            {
                Separate(text, ref first);
                Container(text, options, child, $"public partial struct {Names.Pascal(Names.Split(child, options.Prefixes).Name)}", byOwner, owners, structs, depth + 1);
            }
        }

        text.Append(indent).Append("}\n");
    }

    private static bool HasFunctions(List<Declaration> members)
    {
        foreach (Declaration declaration in members)
        {
            if (declaration.Kind == DeclarationKind.Function)
            {
                return true;
            }
        }

        return false;
    }

    private static void Separate(StringBuilder text, ref bool first)
    {
        if (!first)
        {
            text.Append('\n');
        }

        first = false;
    }

    private static void Indented(StringBuilder text, string body, int depth)
    {
        string indent = new(' ', depth * 4);
        foreach (string line in body.TrimEnd('\n').Split('\n'))
        {
            if (line.Length > 0)
            {
                text.Append(indent);
            }

            text.Append(line).Append('\n');
        }
    }
}
